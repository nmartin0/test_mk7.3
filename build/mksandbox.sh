#!/bin/sh
# SPDX-FileCopyrightText: 2026 Nicholas Martin
#
# Prepare the ODE sandbox for building OSFMK 7.3.
#
#   ODE4LINUX=~/ode4linux sh build/mksandbox.sh
#
# ODE builds inside a "sandbox": a directory holding src, obj, export and
# the rc_files that configure it. OSFMK ships the sandbox layout already
# (osfmk7.3/osfmk/{src,rc_files,link,tools}) and a sandboxrc.template.
#
# Two problems have to be solved, and both are solved with symlinks that
# .gitignore covers, so `git status` stays clean after a full build.
#
# 1. ODE derives the object and export directories from the sandbox base,
#    which would put them inside this repository. They are symlinked out
#    to ${MK_BUILD} instead. Symlinking the other way round -- sandbox in
#    MK_BUILD with src pointing here -- does NOT work: ODE computes the
#    object directory with relative paths (../../../obj/...), the shell
#    resolves the symlink, and the walk up escapes into the wrong tree.
#
# 2. osfmk7.3/osfmk/src/makedefs is an incomplete ODE installation. Its
#    osf.rules.mk includes osf.man.mk and osf.doc.mk, and ODE make needs
#    sys.mk, none of which are present -- OSF expected them from the
#    installed ODE. They are symlinked in from ode4linux. This completes
#    an installation rather than modifying OSFMK.
#
#    (osf.rules.mk also includes osf.sectest.mk, which exists nowhere.
#    That include is guarded by .if ${.TARGETS} == "tdinst_all", a target
#    we never build, so it does not matter.)
set -e

: "${ODE4LINUX:?set ODE4LINUX to your ode4linux clone}"
: "${MK_BUILD:=${HOME}/.cache/mk7.3}"

REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || REPO_ROOT=$(pwd)
OSFMK="${REPO_ROOT}/osfmk7.3/osfmk"

[ -d "${OSFMK}/src" ] || {
	echo "no osfmk7.3/osfmk/src -- has the vendor import been committed?" >&2
	exit 1
}

# --- 1. object and export trees, outside the repository ----------------
mkdir -p "${MK_BUILD}/obj/at386" "${MK_BUILD}/export/at386"
ln -sfn "${MK_BUILD}/obj" "${OSFMK}/obj"
ln -sfn "${MK_BUILD}/export/at386" "${OSFMK}/export/at386"

# --- 2. complete the ODE rule installation -----------------------------
for f in sys.mk osf.man.mk osf.doc.mk; do
	[ -f "${ODE4LINUX}/src/ode/mk/${f}" ] || {
		echo "${f} not found in ${ODE4LINUX}/src/ode/mk" >&2
		exit 1
	}
	ln -sfn "${ODE4LINUX}/src/ode/mk/${f}" "${OSFMK}/src/makedefs/${f}"
done

# --- 3. Buildconf.local ------------------------------------------------
# Buildconf sets SOURCEDIR to the empty string, which assumes a sandbox
# with a backing chain -- OSF's shared read-only source tree, reached via
# backing_build in sb.conf. We have no backing chain: the sources are
# local. With SOURCEDIR empty, MAKESRCDIRPATH (set from it in
# src/Makeconf) is empty too, so after ODE make relocates itself into the
# object directory it has no path back to the source tree and cannot find
# any Makefile. The symptom is misleading: "don't know how to make
# build_all", which looks like a missing target rather than a missing
# search path.
#
# ODE's designed answer is Buildconf.local, which libode/builddata.c
# looks for at <sandbox_base>/rc_files/<project>/Buildconf.local and
# parses AFTER Buildconf, so `replace setenv` here wins. No vendor file
# is modified. Generated rather than committed so that
# git diff <vendor-import>..HEAD -- osfmk7.3/ stays empty.
cat > "${OSFMK}/rc_files/osc/Buildconf.local" <<EOF
#
# Generated by build/mksandbox.sh -- do not edit, and do not commit.
# ODE parses this after Buildconf; see libode/builddata.c.
#
# This sandbox has no backing chain, so the sources are local and
# SOURCEDIR must name them. Buildconf leaves it empty, which is correct
# only for a backed sandbox.
#
replace setenv SOURCEDIR \${source_base}
#
# CARGS is where Buildconf already puts the i386-on-Linux compiler
# arguments, under exactly this condition:
#   on i386 on_os linux target i386 setenv CARGS -D__NO_UNDERSCORES__
# We extend it rather than introduce a new variable. Replacing means
# restating __NO_UNDERSCORES__, which selects ELF symbol naming in
# i386/asm.h and must not be lost.
#
# -m32: Buildconf assumes a 32-bit host, as every host was in 1998. On
# x86-64 its absence silently builds a 64-bit kernel, which first shows
# up as "cast from pointer to integer of different size" in the IPC
# tables -- a real defect, not a warning to suppress.
#
# -Wno-error: conf/template.mk sets -Werror against gcc 2.7.2.1's
# warning set. Modern GCC adds about 25 years of diagnostics OSF never
# saw, so keeping -Werror tightens their configuration rather than
# preserving it. The whole kernel produces 13 warnings in 4 classes
# (-Wpointer-compare, -Wpedantic, -Wexpansion-to-defined, -Woverflow),
# small enough to audit; see AGENTS.md.
#
# -fno-stack-protector, -fno-pic: modern distro GCC defaults to
# -fstack-protector-strong and -fPIE. Both inject symbols a kernel
# cannot resolve. Audited with nm across the built objects: without
# these, every non-trivial object carries undefined __stack_chk_fail_local
# (lives in libssp/libc, absent here) and _GLOBAL_OFFSET_TABLE_ (a
# kernel is loaded at a fixed address and has no dynamic linker). With
# them, both are gone. OSF could not have anticipated either default.
#
# NOT added: -ffreestanding. OSF deliberately passes -fno-builtin from
# conf/AT386/template.mk, and -ffreestanding additionally inhibits
# libcall optimisations. Linux removed -ffreestanding from i386 for
# that reason, preferring targeted -fno-builtin-* flags. -fno-builtin
# plus the kernel's own mem/str routines is the standard arrangement
# and is what OSF chose; leave their choice alone.
replace setenv CARGS "-D__NO_UNDERSCORES__ -m32 -std=gnu89 -fcommon -fno-zero-initialized-in-bss -fno-stack-protector -fno-pic -Wno-error"
#
# The genassym rule in conf/AT386/template.mk calls the compiler
# directly and does NOT include the standard CFLAGS, so nothing from
# CARGS reaches it. genassym computes struct offsets for assym.S, so it
# must be built for the TARGET word size: built 64-bit it would bake
# 8-byte pointer offsets into a 32-bit kernel and crash with no
# diagnostic. It fails loudly instead, on a pointer-to-int cast in
# kern/queue.h. ANSI_CC / TRADITIONAL_CC / HOST_CC are documented hooks
# in makedefs/osf.std.mk, and Buildconf itself sets HOST_CC for the
# i860 target, so this is OSF's own mechanism. -fno-builtin is included
# because that rule drops it too.
#
replace setenv ANSI_CC "gcc -m32 -fno-builtin -Wno-error"
replace setenv TRADITIONAL_CC "gcc -m32 -fno-builtin -Wno-error"
replace setenv HOST_CC "gcc -m32 -fno-builtin -Wno-error"
#
# ld on an x86-64 host defaults to elf_x86_64 output and rejects the
# 32-bit objects: "i386 architecture of input file is incompatible with
# i386:x86-64 output". This is the link-stage counterpart of -m32 and
# the same 1998 assumption that host word size equals target.
# conf/AT386/template.mk ends its LDFLAGS with "LDFLAGS+=${LDOPTS}",
# which exists precisely so the link can be extended without editing
# the template.
#
replace setenv LDOPTS "-m elf_i386"
EOF

# --- 4. the sandboxrc --------------------------------------------------
# Derived from osfmk7.3/sandboxrc.template, with the base pointing at
# this checkout instead of /usr/src/DR3. Kept outside the repository.
cat > "${MK_BUILD}/sandboxrc" <<EOF
	# sandbox rc file, generated by build/mksandbox.sh

	# default sandbox
default osfmk

	# base directories to sandboxes
base * ${REPO_ROOT}/osfmk7.3

	# list of sandboxes
sb osfmk
EOF

echo "sandbox ready."
echo "  obj    -> ${MK_BUILD}/obj"
echo "  export -> ${MK_BUILD}/export/at386"
echo "  rc     :  ${MK_BUILD}/sandboxrc"
echo

if [ -x "${MK_BUILD}/ode-sandbox/tools/at386_linux/bin/build" ]; then
	echo "Next:"
	echo "  sh build/ode.sh MAKEFILE_PASS=FIRST"
else
	echo "The ODE tools are not built yet. Next:"
	echo "  sh build/bootstrap-ode.sh"
	echo "  sh build/ode.sh MAKEFILE_PASS=FIRST"
fi
